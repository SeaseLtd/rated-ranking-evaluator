"""
Pydantic models for the LLM service interface and validation logic.
"""

import json
from typing import List
from pydantic import BaseModel, Field, model_validator

# ───────────────────────────────────────────────────────────────
# Response model for LLM-generated output
# ───────────────────────────────────────────────────────────────

class LLMQueryResponse(BaseModel):
    """
    Output model for responses from the LLM service.
    
    Attributes:
        content (str): Raw content generated by the LLM as a JSON-encoded string.
        content_list (List[str]): Parsed list of strings extracted from `content`.
    """
    content: str = Field(..., description="Raw response content as a JSON string representing a list of strings.")
    content_list: List[str] = Field(default_factory=list, description="Parsed list of strings from the JSON content.")

    @model_validator(mode="after")
    def validate_and_parse_content(self) -> 'LLMQueryResponse':
        """
        Parses and validates the `content` field to populate `content_list`.
        Ensures it's a JSON-encoded list of non-empty strings.
        """
        try:
            parsed = json.loads(self.content)
        except json.JSONDecodeError as e:
            raise ValueError(f"Invalid JSON in `content`: {e}")

        if not isinstance(parsed, list):
            raise ValueError("`content` must be a JSON list.")

        if not all(isinstance(item, str) for item in parsed):
            raise ValueError("All items in `content` must be strings.")

        if any(item.strip() == "" for item in parsed):
            raise ValueError("Empty or whitespace-only strings are not allowed in `content`.")

        self.content_list = parsed
        return self